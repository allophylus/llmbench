#!/usr/bin/env python3
"""Rewrite the sticky topbar of the hand-maintained root index.html.

index.html is not generated by build_pages.py, so its header nav is refreshed
here from scripts/site_nav.py. Only the bytes between the topbar markers are
touched — table markup, controls and scripts are never modified.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import site_nav  # noqa: E402

ROOT = site_nav.ROOT
PATH = os.path.join(ROOT, "index.html")
START = "<!-- topbar:start"
END = "<!-- topbar:end -->"


def main():
    html = open(PATH, encoding="utf-8").read()
    if START not in html or END not in html:
        print("index.html has no site-nav markers — refusing to guess")
        return 1
    a = html.index(START)
    b = html.index(END) + len(END)
    block = (START + " (generated by scripts/site_nav.py — run scripts/refresh_nav.py) -->\n"
             + site_nav.render_topbar("", "overview", style="site") + "\n" + END)
    old = html[a:b]
    if old == block:
        print("index.html nav already canonical")
        return 0
    open(PATH, "w", encoding="utf-8").write(html[:a] + block + html[b:])
    print("index.html nav refreshed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
