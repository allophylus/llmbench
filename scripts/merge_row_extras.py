#!/usr/bin/env python3
"""merge_row_extras.py — attach the context-sweep and logic-trap results to the
Overview rows, so both live in the model's row instead of on their own pages.

Reads data/results.json (already built by update_data.py + a3b_extras.py) and adds:
  row["sweep"] = {"4096": {prefill_tps, decode_tps, vram_peak_gib, prompt_tokens, predicted_n, status}, ...}
  row["logic"] = {"off": {correct, n, tokens}, "on": {...}}   (invalid arms marked)
Writes data/results.json and data/results.js unchanged in shape otherwise.
"""
import json, os, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")

def load(p):
    with open(p, encoding="utf-8") as f:
        return json.load(f)

def sweep_for(slug):
    p = os.path.join(ROOT, "benchmarks", "ctx-sweep", slug + ".json")
    if not os.path.exists(p):
        return None
    cells = load(p).get("cells") or {}
    out = {}
    for rung, c in cells.items():
        if not isinstance(c, dict):
            continue
        ok = (c.get("status") == "ok" and (c.get("predicted_n") or 0) > 0)
        out[str(rung)] = {
            "prefill": c.get("prefill_tps") if ok else None,
            "decode": c.get("decode_tps") if ok else None,
            "vram": c.get("vram_peak_gib"),
            "prompt": c.get("prompt_tokens_client"),
            "status": c.get("status"),
        }
    return out or None

def logic_for(slug):
    p = os.path.join(ROOT, "benchmarks", "logic10", "results", slug + ".json")
    if not os.path.exists(p):
        return None
    modes = load(p).get("modes") or {}
    out = {}
    for mode, v in modes.items():
        s = (v or {}).get("summary") or {}
        valid = (s.get("tokens") or 0) > 0 and (s.get("scored") or 0) > 0
        out[mode] = {
            "correct": s.get("correct") if valid else None,
            "n": s.get("n") if valid else None,
            "tokens": s.get("tokens") if valid else None,
            "status": "ok" if valid else "invalid",
        }
    return out or None

def main():
    doc = load(os.path.join(DATA, "results.json"))
    n_s = n_l = 0
    for r in doc.get("rows", []):
        slug = r.get("slug") or ""
        sw = sweep_for(slug)
        lg = logic_for(slug)
        if sw:
            r["sweep"] = sw; n_s += 1
        if lg:
            r["logic"] = lg; n_l += 1
    with open(os.path.join(DATA, "results.json"), "w", encoding="utf-8") as f:
        json.dump(doc, f, indent=1)
    with open(os.path.join(DATA, "results.js"), "w", encoding="utf-8") as f:
        f.write("// generated by scripts/update_data.py + merge_row_extras.py — do not hand-edit\n")
        f.write("window.LLMBENCH_DATA = " + json.dumps(doc, separators=(",", ":")) + ";\n")
    print(f"attached: sweep to {n_s} row(s), logic to {n_l} row(s)")

if __name__ == "__main__":
    main()
