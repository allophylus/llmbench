#!/usr/bin/env python3
"""render_results.py — build RESULTS.md from the arm JSONs.

Reads every arms/<slug>/arm-<X>.json produced by ablate3.py and writes RESULTS.md with
ONE ROW PER MODEL (measurements grouped as sub-rows under the model), which is the same
reading pattern as the models table on the site.

Usage: render_results.py <arms-dir> <out-md> [--date YYYY-MM-DD]
"""
import json, os, sys, time

ORDER = ["A-baseline", "B-fa-off", "C-draft-mtp", "E-mtp-ngram", "D-draft-dflash", "D2-dflash-nm7"]
LABEL = {"A-baseline": "A baseline (FA on, no spec)",
         "B-fa-off": "B FA off",
         "C-draft-mtp": "C draft-mtp n7",
         "D-draft-dflash": "D draft-dflash (default n)",
         "D2-dflash-nm7": "D2 draft-dflash n7",
         "E-mtp-ngram": "E draft-mtp + ngram-cache"}
PRETTY = {"qwen3-8-27b-q4km": "Qwen3.8-27B Q4_K_M",
          "qwen3-8-27b-q4-0": "Qwen3.8-27B Q4_0",
          "davidau-qwen3-8-27b-neo-max-mtp-q4-k-m": "DavidAU NEO-MAX MTP Q4_K_M",
          "huihui-abl-q4-k-m": "Huihui abl Q4_K_M",
          "qwen3-6-35b-a3b-ud-q4km": "Qwen3.6-35B-A3B UD-Q4_K_M",
          "ornith-1-5-35b-a3b-q4-k-m": "Ornith-1.5-35B-A3B Q4_K_M",
          "lfm3-1-7b-q4-k-m": "LFM3-1.7B Q4_K_M"}


def load(arms):
    models = {}
    for slug in sorted(os.listdir(arms)):
        d = os.path.join(arms, slug)
        if not os.path.isdir(d):
            continue
        recs = {}
        for f in os.listdir(d):
            if f.startswith("arm-") and f.endswith(".json"):
                r = json.load(open(os.path.join(d, f)))
                recs[r["arm"]] = r
        if recs:
            models[slug] = recs
    return models


def fnum(x, fmt="%.1f"):
    return "—" if x is None else fmt % x


def row_cells(r):
    if r.get("status") == "not-applicable":
        return ["n/a"] * 9 + ["n/a"]
    if r.get("status") == "void":
        return ["VOID"] * 9 + ["VOID"]
    s = r.get("decode_short") or {}
    l = r.get("decode_30k") or {}
    return [fnum(s.get("decode_tps")), fnum(l.get("decode_tps")),
            fnum(s.get("prefill_tps"), "%.0f"), fnum(l.get("prefill_tps"), "%.0f"),
            fnum(r.get("vram_idle_gib"), "%.2f"),
            fnum(max(x for x in (s.get("vram_peak_gib"), l.get("vram_peak_gib")) if x is not None)
                 if any(x is not None for x in (s.get("vram_peak_gib"), l.get("vram_peak_gib"))) else None,
                 "%.2f"),
            str(s.get("prompt_tokens") or "—"), str(l.get("prompt_n") or "—"),
            ""]


def main():
    arms, out = sys.argv[1], sys.argv[2]
    models = load(arms)
    date = sys.argv[3] if len(sys.argv) > 3 else time.strftime("%Y-%m-%d")
    L = []
    L.append("# Accelerator ablation across every runnable model — R9700, llama.cpp Vulkan\n")
    L.append("Date: %s. Host: one AMD Radeon AI PRO R9700 (32 GiB, RADV). Grid generated by "
             "`ablate3.py`; one MODEL per group, arms as sub-rows.\n" % date)
    L.append("## Main table (one row per model)\n")
    L.append("| model | arm | decode 1.6k t/s | decode 27.7k t/s | prefill 1.6k t/s | "
             "prefill 27.7k t/s | VRAM peak GiB | prompt tokens 1.6k / 27.7k | answers match baseline |")
    L.append("|:--|:--|--:|--:|--:|--:|--:|:--|:--|")
    for slug, recs in models.items():
        name = PRETTY.get(slug, slug)
        base = recs.get("A-baseline") or {}
        b_ans = base.get("answers") or {}
        first = True
        for arm in ORDER:
            r = recs.get(arm)
            if not r:
                continue
            label = LABEL[arm]
            if r.get("status") == "not-applicable":
                L.append("| **%s** | %s | not applicable | — | — | — | — | | %s |"
                         % (name if first else "", label,
                            r.get("reason", "").replace("|", "/")))
                first = False
                continue
            if r.get("status") == "void":
                L.append("| **%s** | %s | VOID | VOID | VOID | VOID | VOID | | %s |"
                         % (name if first else "", label, r.get("void_reason", "").replace("|", "/")))
                first = False
                continue
            s = r.get("decode_short") or {}
            l = r.get("decode_30k") or {}
            peaks = [x for x in (s.get("vram_peak_gib"), l.get("vram_peak_gib")) if x is not None]
            # answer match vs baseline
            if arm == "A-baseline":
                match = "— (reference)"
            else:
                a_ans = r.get("answers") or {}
                same = sum(1 for k in b_ans if k in a_ans and a_ans[k].get("content") == b_ans[k].get("content"))
                match = "%d/%d" % (same, len(b_ans))
            cells = [fnum(s.get("decode_tps")), fnum(l.get("decode_tps")),
                     fnum(s.get("prefill_tps"), "%.0f"), fnum(l.get("prefill_tps"), "%.0f"),
                     fnum(max(peaks) if peaks else None, "%.2f"),
                     "%s / %s" % (s.get("prompt_tokens") or "—", l.get("prompt_n") or "—"),
                     match]
            L.append("| **%s** | %s | %s |" % (name if first else "", label, " | ".join(cells)))
            first = False
    open(out, "w").write("\n".join(L) + "\n")
    print("wrote", out, len(models), "models")


if __name__ == "__main__":
    main()
